CREATE TABLE IF NOT EXISTS album (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    visibility VARCHAR(16) NOT NULL DEFAULT 'PRIVATE' CHECK (visibility IN ('PRIVATE', 'PUBLIC')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS album_section (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id BIGINT NOT NULL REFERENCES album(id),
    collection_key VARCHAR(32) NOT NULL,
    page_count INTEGER NOT NULL DEFAULT 1 CHECK (page_count >= 1),
    CONSTRAINT album_section_key_uq UNIQUE (album_id, collection_key),
    CONSTRAINT album_section_key_check CHECK (collection_key IN ('NBA', 'MY_LITTLE_PONY', 'CARS', 'MARVEL'))
);
CREATE TABLE IF NOT EXISTS album_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL REFERENCES album_section(id),
    page_number INTEGER NOT NULL CHECK (page_number >= 1),
    slot_index INTEGER NOT NULL CHECK (slot_index BETWEEN 0 AND 8),
    name VARCHAR(255) NOT NULL,
    image_url VARCHAR(2048) NOT NULL,
    origin VARCHAR(16) NOT NULL CHECK (origin IN ('MANUAL', 'PURCHASE')),
    order_item_id BIGINT REFERENCES order_item(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT album_card_slot_uq UNIQUE (section_id, page_number, slot_index),
    CONSTRAINT album_card_purchase_origin_check CHECK (
        (origin = 'PURCHASE' AND order_item_id IS NOT NULL)
        OR (origin = 'MANUAL' AND order_item_id IS NULL)
    )
);
CREATE INDEX IF NOT EXISTS album_card_section_idx ON album_card(section_id);
CREATE INDEX IF NOT EXISTS album_card_order_item_idx ON album_card(order_item_id);
